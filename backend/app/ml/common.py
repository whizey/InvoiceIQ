"""Shared evaluation core for the RecoverIQ late-payment models.

The three trainers — train_xgboost.py, train_random_forest.py,
train_gradient_boosting.py — each own their model and nothing else. Data
loading, the metric definitions, the fold construction and the stability
check all live here, imported by all three.

That split is deliberate. The six scripts this replaced each carried their
own copy of the split loading and scoring, drifted apart, and ended up
reporting numbers that were not comparable with one another: one trained
on late_payment_strict while the pipeline declared
late_payment_weekend_adjusted canonical, and the committed metrics had
been generated by a still older version. A comparison table is only worth
reading if every row was produced by the same code.

WHY THE HEADLINE METRIC IS WITHIN-PERIOD AUC
--------------------------------------------
The late rate moves hard across the validation window:

    2015-10   63.2%
    2015-11   39.0%
    2015-12   29.7%

Pooled ROC-AUC over a window like that conflates two questions — "is this
invoice riskier than that one" and "is this month riskier than that
month" — and a model with no access to the period cannot answer the
second. The effect is big enough to invert the metric: one run scored
0.5481 pooled while every individual month inside it scored 0.57-0.61. A
pooled figure below every one of its own components is measuring drift,
not skill.

So within_period_auc ranks invoices only against others posted in the
same month, weighted by month size. pooled_roc_auc is still reported,
because omitting it would be its own kind of dishonesty, but it is not
what models are selected on.
"""

