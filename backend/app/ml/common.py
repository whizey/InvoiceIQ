def write_report(model_slug: str, report: dict) -> Path:
    directory = ARTIFACT_ROOT / model_slug
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / "report.json"
    path.write_text(json.dumps(report, indent=2) + "\n")
    return path


